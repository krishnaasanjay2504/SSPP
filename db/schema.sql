-- Smart Student Placement Portal - Oracle AI Database schema
-- All tables are prefixed SP_ so they never collide with objects in the SYSTEM schema.

CREATE TABLE IF NOT EXISTS sp_users (
  id            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email         VARCHAR2(150) NOT NULL UNIQUE,
  password_hash VARCHAR2(300) NOT NULL,
  full_name     VARCHAR2(150) NOT NULL,
  user_role     VARCHAR2(20)  NOT NULL CHECK (user_role IN ('STUDENT','TPO','FACULTY','RECRUITER','ALUMNI','ADMIN')),
  phone         VARCHAR2(20),
  company_id    NUMBER,
  designation   VARCHAR2(120),
  is_active     NUMBER(1) DEFAULT 1,
  is_approved   NUMBER(1) DEFAULT 1,
  last_login    TIMESTAMP,
  created_at    TIMESTAMP DEFAULT SYSTIMESTAMP
);

CREATE TABLE IF NOT EXISTS sp_students (
  user_id          NUMBER PRIMARY KEY REFERENCES sp_users(id) ON DELETE CASCADE,
  reg_no           VARCHAR2(30),
  department       VARCHAR2(20),
  batch_year       NUMBER(4),
  gender           VARCHAR2(10),
  dob              DATE,
  address          VARCHAR2(400),
  cgpa             NUMBER(4,2),
  tenth_pct        NUMBER(5,2),
  twelfth_pct      NUMBER(5,2),
  active_backlogs  NUMBER(3) DEFAULT 0,
  history_backlogs NUMBER(3) DEFAULT 0,
  career_goal      VARCHAR2(100),
  interests        VARCHAR2(500),
  summary          VARCHAR2(2000),
  github           VARCHAR2(200),
  linkedin         VARCHAR2(200),
  leetcode         VARCHAR2(200),
  hackerrank       VARCHAR2(200),
  portfolio        VARCHAR2(200),
  placement_status VARCHAR2(20) DEFAULT 'NOT_PLACED',
  updated_at       TIMESTAMP DEFAULT SYSTIMESTAMP
);

-- Education, skills, certifications, projects, internships, achievements, hackathons,
-- workshops, activities and languages share one flexible table.
CREATE TABLE IF NOT EXISTS sp_profile_items (
  id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     NUMBER NOT NULL REFERENCES sp_users(id) ON DELETE CASCADE,
  item_type   VARCHAR2(20) NOT NULL,
  title       VARCHAR2(200) NOT NULL,
  org         VARCHAR2(200),
  description VARCHAR2(4000),
  start_label VARCHAR2(30),
  end_label   VARCHAR2(30),
  url         VARCHAR2(300),
  item_level  VARCHAR2(30),
  score       VARCHAR2(30),
  tech        VARCHAR2(300),
  created_at  TIMESTAMP DEFAULT SYSTIMESTAMP
);

CREATE TABLE IF NOT EXISTS sp_resumes (
  id             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id        NUMBER NOT NULL REFERENCES sp_users(id) ON DELETE CASCADE,
  title          VARCHAR2(120) NOT NULL,
  template_code  VARCHAR2(30) DEFAULT 'modern',
  target_role    VARCHAR2(120),
  objective      VARCHAR2(2000),
  sections       VARCHAR2(500),
  excluded_items VARCHAR2(4000),
  created_at     TIMESTAMP DEFAULT SYSTIMESTAMP,
  updated_at     TIMESTAMP DEFAULT SYSTIMESTAMP
);

CREATE TABLE IF NOT EXISTS sp_companies (
  id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name         VARCHAR2(150) NOT NULL,
  industry     VARCHAR2(100),
  website      VARCHAR2(200),
  about        VARCHAR2(2000),
  hq_location  VARCHAR2(120),
  status       VARCHAR2(20) DEFAULT 'PENDING',
  created_by   NUMBER,
  created_at   TIMESTAMP DEFAULT SYSTIMESTAMP
);

CREATE TABLE IF NOT EXISTS sp_drives (
  id                   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id           NUMBER NOT NULL REFERENCES sp_companies(id),
  job_role             VARCHAR2(150) NOT NULL,
  job_desc             CLOB,
  job_type             VARCHAR2(20) DEFAULT 'FULL_TIME',
  ctc_lpa              NUMBER(6,2),
  locations            VARCHAR2(300),
  min_cgpa             NUMBER(4,2) DEFAULT 0,
  min_tenth            NUMBER(5,2) DEFAULT 0,
  min_twelfth          NUMBER(5,2) DEFAULT 0,
  branches             VARCHAR2(200),
  batch_year           NUMBER(4),
  max_active_backlogs  NUMBER(3) DEFAULT 0,
  max_history_backlogs NUMBER(3) DEFAULT 99,
  required_skills      VARCHAR2(500),
  rounds               VARCHAR2(400) DEFAULT 'Aptitude Test,Coding Test,Technical Interview,HR Interview',
  reg_deadline         TIMESTAMP,
  drive_date           TIMESTAMP,
  venue                VARCHAR2(200),
  status               VARCHAR2(20) DEFAULT 'PENDING_APPROVAL',
  created_by           NUMBER,
  created_at           TIMESTAMP DEFAULT SYSTIMESTAMP
);

CREATE TABLE IF NOT EXISTS sp_applications (
  id            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  drive_id      NUMBER NOT NULL REFERENCES sp_drives(id) ON DELETE CASCADE,
  student_id    NUMBER NOT NULL REFERENCES sp_users(id) ON DELETE CASCADE,
  status        VARCHAR2(20) DEFAULT 'APPLIED',
  current_round VARCHAR2(80),
  remarks       VARCHAR2(1000),
  resume_id     NUMBER,
  applied_at    TIMESTAMP DEFAULT SYSTIMESTAMP,
  updated_at    TIMESTAMP DEFAULT SYSTIMESTAMP,
  CONSTRAINT sp_app_uq UNIQUE (drive_id, student_id)
);

CREATE TABLE IF NOT EXISTS sp_app_history (
  id             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  application_id NUMBER NOT NULL REFERENCES sp_applications(id) ON DELETE CASCADE,
  status         VARCHAR2(20),
  note           VARCHAR2(1000),
  changed_by     NUMBER,
  changed_at     TIMESTAMP DEFAULT SYSTIMESTAMP
);

CREATE TABLE IF NOT EXISTS sp_events (
  id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title       VARCHAR2(200) NOT NULL,
  event_type  VARCHAR2(30) NOT NULL,
  start_at    TIMESTAMP NOT NULL,
  end_at      TIMESTAMP,
  drive_id    NUMBER REFERENCES sp_drives(id) ON DELETE CASCADE,
  description VARCHAR2(2000),
  venue       VARCHAR2(200),
  created_by  NUMBER,
  created_at  TIMESTAMP DEFAULT SYSTIMESTAMP
);

CREATE TABLE IF NOT EXISTS sp_event_attendance (
  event_id  NUMBER REFERENCES sp_events(id) ON DELETE CASCADE,
  user_id   NUMBER REFERENCES sp_users(id) ON DELETE CASCADE,
  marked_at TIMESTAMP DEFAULT SYSTIMESTAMP,
  CONSTRAINT sp_att_pk PRIMARY KEY (event_id, user_id)
);

CREATE TABLE IF NOT EXISTS sp_notif_prefs (
  user_id  NUMBER PRIMARY KEY REFERENCES sp_users(id) ON DELETE CASCADE,
  offsets  VARCHAR2(100) DEFAULT '10080,2880,1440,60',
  email_on NUMBER(1) DEFAULT 1,
  sms_on   NUMBER(1) DEFAULT 0,
  inapp_on NUMBER(1) DEFAULT 1
);

CREATE TABLE IF NOT EXISTS sp_notifications (
  id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    NUMBER NOT NULL REFERENCES sp_users(id) ON DELETE CASCADE,
  title      VARCHAR2(200),
  message    VARCHAR2(1000),
  link       VARCHAR2(300),
  category   VARCHAR2(30),
  is_read    NUMBER(1) DEFAULT 0,
  dedupe_key VARCHAR2(200),
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP
);

CREATE TABLE IF NOT EXISTS sp_offcampus (
  id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company     VARCHAR2(150) NOT NULL,
  job_role    VARCHAR2(150) NOT NULL,
  description CLOB,
  skills      VARCHAR2(500),
  category    VARCHAR2(50),
  job_type    VARCHAR2(30),
  experience  VARCHAR2(50),
  batch       VARCHAR2(50),
  ctc         VARCHAR2(60),
  location    VARCHAR2(200),
  work_mode   VARCHAR2(20),
  deadline    DATE,
  apply_url   VARCHAR2(400),
  source      VARCHAR2(120),
  verified    NUMBER(1) DEFAULT 0,
  status      VARCHAR2(20) DEFAULT 'PENDING',
  posted_by   NUMBER,
  created_at  TIMESTAMP DEFAULT SYSTIMESTAMP
);

CREATE TABLE IF NOT EXISTS sp_saved_jobs (
  user_id NUMBER REFERENCES sp_users(id) ON DELETE CASCADE,
  job_id  NUMBER REFERENCES sp_offcampus(id) ON DELETE CASCADE,
  CONSTRAINT sp_saved_pk PRIMARY KEY (user_id, job_id)
);

CREATE TABLE IF NOT EXISTS sp_offers (
  id             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id     NUMBER NOT NULL REFERENCES sp_users(id) ON DELETE CASCADE,
  application_id NUMBER,
  company_name   VARCHAR2(150),
  job_role       VARCHAR2(150),
  ctc_lpa        NUMBER(6,2),
  location       VARCHAR2(150),
  joining_date   DATE,
  accept_by      DATE,
  offer_letter   VARCHAR2(300),
  source         VARCHAR2(20) DEFAULT 'CAMPUS',
  status         VARCHAR2(20) DEFAULT 'PENDING',
  created_by     NUMBER,
  created_at     TIMESTAMP DEFAULT SYSTIMESTAMP
);

CREATE TABLE IF NOT EXISTS sp_paths (
  id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        VARCHAR2(120) NOT NULL,
  skill_tag   VARCHAR2(40),
  description VARCHAR2(1000),
  icon        VARCHAR2(40),
  color       VARCHAR2(20),
  seq         NUMBER DEFAULT 0
);

CREATE TABLE IF NOT EXISTS sp_path_steps (
  id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  path_id      NUMBER NOT NULL REFERENCES sp_paths(id) ON DELETE CASCADE,
  seq          NUMBER,
  title        VARCHAR2(200),
  content_kind VARCHAR2(20),
  content      CLOB,
  resource_url VARCHAR2(400),
  quiz_id      NUMBER
);

CREATE TABLE IF NOT EXISTS sp_step_progress (
  user_id      NUMBER REFERENCES sp_users(id) ON DELETE CASCADE,
  step_id      NUMBER REFERENCES sp_path_steps(id) ON DELETE CASCADE,
  completed_at TIMESTAMP DEFAULT SYSTIMESTAMP,
  CONSTRAINT sp_prog_pk PRIMARY KEY (user_id, step_id)
);

CREATE TABLE IF NOT EXISTS sp_quizzes (
  id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title        VARCHAR2(200) NOT NULL,
  category     VARCHAR2(20),
  topic        VARCHAR2(60),
  company      VARCHAR2(100),
  duration_min NUMBER DEFAULT 15,
  description  VARCHAR2(1000),
  is_active    NUMBER(1) DEFAULT 1,
  created_by   NUMBER,
  created_at   TIMESTAMP DEFAULT SYSTIMESTAMP
);

CREATE TABLE IF NOT EXISTS sp_questions (
  id            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  quiz_id       NUMBER NOT NULL REFERENCES sp_quizzes(id) ON DELETE CASCADE,
  qtype         VARCHAR2(10) DEFAULT 'MCQ',
  question_text VARCHAR2(4000),
  options_json  VARCHAR2(4000),
  answer        VARCHAR2(500),
  explanation   VARCHAR2(4000),
  topic         VARCHAR2(60),
  marks         NUMBER DEFAULT 1
);

CREATE TABLE IF NOT EXISTS sp_attempts (
  id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  quiz_id      NUMBER NOT NULL REFERENCES sp_quizzes(id) ON DELETE CASCADE,
  user_id      NUMBER NOT NULL REFERENCES sp_users(id) ON DELETE CASCADE,
  score        NUMBER,
  max_score    NUMBER,
  accuracy     NUMBER(5,2),
  time_sec     NUMBER,
  answers_json CLOB,
  topic_json   VARCHAR2(4000),
  submitted_at TIMESTAMP DEFAULT SYSTIMESTAMP
);

CREATE TABLE IF NOT EXISTS sp_forum_questions (
  id                 NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id            NUMBER REFERENCES sp_users(id) ON DELETE CASCADE,
  title              VARCHAR2(300) NOT NULL,
  body               CLOB,
  tags               VARCHAR2(300),
  views              NUMBER DEFAULT 0,
  accepted_answer_id NUMBER,
  audience           VARCHAR2(20) DEFAULT 'ALL',
  created_at         TIMESTAMP DEFAULT SYSTIMESTAMP
);

CREATE TABLE IF NOT EXISTS sp_forum_answers (
  id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  question_id NUMBER REFERENCES sp_forum_questions(id) ON DELETE CASCADE,
  user_id     NUMBER REFERENCES sp_users(id) ON DELETE CASCADE,
  body        CLOB,
  is_verified NUMBER(1) DEFAULT 0,
  created_at  TIMESTAMP DEFAULT SYSTIMESTAMP
);

CREATE TABLE IF NOT EXISTS sp_forum_comments (
  id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  target_type VARCHAR2(1),
  target_id   NUMBER,
  user_id     NUMBER REFERENCES sp_users(id) ON DELETE CASCADE,
  body        VARCHAR2(1000),
  created_at  TIMESTAMP DEFAULT SYSTIMESTAMP
);

CREATE TABLE IF NOT EXISTS sp_votes (
  user_id     NUMBER,
  target_type VARCHAR2(1),
  target_id   NUMBER,
  vote_val    NUMBER(1),
  CONSTRAINT sp_votes_pk PRIMARY KEY (user_id, target_type, target_id)
);

CREATE TABLE IF NOT EXISTS sp_bookmarks (
  user_id     NUMBER,
  question_id NUMBER REFERENCES sp_forum_questions(id) ON DELETE CASCADE,
  CONSTRAINT sp_bm_pk PRIMARY KEY (user_id, question_id)
);

CREATE TABLE IF NOT EXISTS sp_tag_follows (
  user_id NUMBER,
  tag     VARCHAR2(40),
  CONSTRAINT sp_tf_pk PRIMARY KEY (user_id, tag)
);

CREATE TABLE IF NOT EXISTS sp_interview_questions (
  id            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category      VARCHAR2(20),
  topic         VARCHAR2(60),
  company       VARCHAR2(100),
  question_text VARCHAR2(1000),
  model_answer  VARCHAR2(4000),
  tips          VARCHAR2(1000),
  keywords      VARCHAR2(500)
);

CREATE TABLE IF NOT EXISTS sp_interview_sessions (
  id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    NUMBER REFERENCES sp_users(id) ON DELETE CASCADE,
  category   VARCHAR2(20),
  topic      VARCHAR2(60),
  avg_score  NUMBER(5,2),
  completed  NUMBER(1) DEFAULT 0,
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP
);

CREATE TABLE IF NOT EXISTS sp_interview_answers (
  id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id  NUMBER REFERENCES sp_interview_sessions(id) ON DELETE CASCADE,
  question_id NUMBER,
  response    VARCHAR2(4000),
  score       NUMBER(4,1),
  feedback    VARCHAR2(4000),
  created_at  TIMESTAMP DEFAULT SYSTIMESTAMP
);

CREATE TABLE IF NOT EXISTS sp_problems (
  id             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title          VARCHAR2(200),
  difficulty     VARCHAR2(10),
  topic          VARCHAR2(60),
  statement      CLOB,
  input_format   VARCHAR2(1000),
  output_format  VARCHAR2(1000),
  samples_json   CLOB,
  tests_json     CLOB,
  solution       CLOB,
  starter_code   VARCHAR2(2000),
  points         NUMBER DEFAULT 10
);

CREATE TABLE IF NOT EXISTS sp_submissions (
  id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  problem_id   NUMBER REFERENCES sp_problems(id) ON DELETE CASCADE,
  user_id      NUMBER REFERENCES sp_users(id) ON DELETE CASCADE,
  lang         VARCHAR2(20),
  code         CLOB,
  passed       NUMBER,
  total        NUMBER,
  verdict      VARCHAR2(30),
  submitted_at TIMESTAMP DEFAULT SYSTIMESTAMP
);

CREATE TABLE IF NOT EXISTS sp_announcements (
  id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title      VARCHAR2(200),
  body       CLOB,
  category   VARCHAR2(30),
  link       VARCHAR2(400),
  created_by NUMBER,
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP
);

CREATE TABLE IF NOT EXISTS sp_experiences (
  id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     NUMBER REFERENCES sp_users(id) ON DELETE CASCADE,
  company     VARCHAR2(150),
  job_role    VARCHAR2(150),
  exp_year    NUMBER(4),
  rounds_desc VARCHAR2(1000),
  content     CLOB,
  rating      NUMBER(1),
  tips        VARCHAR2(2000),
  outcome     VARCHAR2(20),
  created_at  TIMESTAMP DEFAULT SYSTIMESTAMP
);

CREATE TABLE IF NOT EXISTS sp_mentorship (
  id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id NUMBER REFERENCES sp_users(id) ON DELETE CASCADE,
  mentor_id  NUMBER REFERENCES sp_users(id) ON DELETE CASCADE,
  topic      VARCHAR2(200),
  message    VARCHAR2(4000),
  reply      VARCHAR2(4000),
  status     VARCHAR2(20) DEFAULT 'OPEN',
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP,
  replied_at TIMESTAMP
);

CREATE TABLE IF NOT EXISTS sp_tickets (
  id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    NUMBER REFERENCES sp_users(id) ON DELETE CASCADE,
  subject    VARCHAR2(200),
  body       VARCHAR2(4000),
  category   VARCHAR2(40),
  status     VARCHAR2(20) DEFAULT 'OPEN',
  response   VARCHAR2(4000),
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP,
  updated_at TIMESTAMP DEFAULT SYSTIMESTAMP
);

CREATE TABLE IF NOT EXISTS sp_feedback (
  id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    NUMBER REFERENCES sp_users(id) ON DELETE CASCADE,
  category   VARCHAR2(40),
  rating     NUMBER(1),
  comments   VARCHAR2(2000),
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP
);

CREATE INDEX IF NOT EXISTS sp_items_user_ix ON sp_profile_items(user_id, item_type);
CREATE INDEX IF NOT EXISTS sp_app_student_ix ON sp_applications(student_id);
CREATE INDEX IF NOT EXISTS sp_notif_user_ix ON sp_notifications(user_id, is_read);
CREATE INDEX IF NOT EXISTS sp_events_start_ix ON sp_events(start_at);
CREATE INDEX IF NOT EXISTS sp_attempts_user_ix ON sp_attempts(user_id);
